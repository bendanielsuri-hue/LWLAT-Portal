#!/usr/bin/env node
// PostToolUse hook (matcher: Bash, filtered to `gh issue create`) — after a new
// ticket is created, classify its weight the same way ticket-settings-check.js
// does and post it as a comment so the suggestion travels with the ticket
// instead of being recomputed (and possibly drifting) each time it's opened.
// Advisory-only, best-effort: never blocks, never fails the triggering command.
const fs = require("fs");
const { execSync } = require("child_process");
const { classifyTicket } = require("./lib/ticket-classify.js");

function withGhOnPath(fn) {
  try {
    return fn(process.env);
  } catch {
    const env = Object.assign({}, process.env, {
      PATH: `${process.env.PATH};C:\\Program Files\\GitHub CLI`,
    });
    return fn(env);
  }
}

const SUGGESTION = {
  heavy: "opus, effort high–xhigh",
  "hard-debug": "opus, effort high–max",
  routine: "sonnet, effort medium–high",
  light: "sonnet, effort low–medium",
};

function main() {
  let input = "";
  try {
    input = fs.readFileSync(0, "utf8");
  } catch {
    return;
  }

  let payload;
  try {
    payload = JSON.parse(input);
  } catch {
    return;
  }

  const command = payload?.tool_input?.command || "";
  if (!/\bgh\s+issue\s+create\b/.test(command)) return;

  // `gh issue create` prints the new issue's URL on success.
  const out = String(payload?.tool_response?.stdout || payload?.tool_response?.output || "");
  const urlMatch = /\/issues\/(\d+)\b/.exec(out);
  if (!urlMatch) return;
  const n = urlMatch[1];

  const issue = withGhOnPath((env) =>
    JSON.parse(
      execSync(`gh issue view ${n} --json title,body,labels,comments`, {
        encoding: "utf8",
        timeout: 8000,
        env,
        stdio: ["ignore", "pipe", "pipe"],
      })
    )
  );
  if (!issue) return;

  const verdict = classifyTicket(issue);
  const suggestion = SUGGESTION[verdict.weight];
  const reasonSuffix = verdict.why ? ` — ${verdict.why}` : "";
  const body = `Suggested settings: ${suggestion}${reasonSuffix}. (Advisory, auto-generated by ticket-create-settings-suggest.js — see docs/agents/claude-code-usage.md.)`;

  try {
    withGhOnPath((env) =>
      execSync(`gh issue comment ${n} --body ${JSON.stringify(body)}`, {
        encoding: "utf8",
        timeout: 8000,
        env,
        stdio: ["ignore", "pipe", "pipe"],
      })
    );
  } catch {
    // best-effort — don't fail the triggering command over a comment post
  }
}

try {
  main();
} catch {
  // never block on a hook bug
}
process.exit(0);
